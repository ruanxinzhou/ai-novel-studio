"""档案密度（archive density）：数字要挂在人/时/物上，不能是孤零零一个数。

## 为什么要单独做这一项

现行规则只要求「每 500 字至少 1 个具体数字」。这条规则测的是**数字本身**，
但人工定稿里的数字几乎全是**档案**：

    机器稿：「邵广勤是闸房维修工，今早猝死，死因还没查清。」
    定　稿：「邵广勤是闸房维修工，四十七岁，住在二楼最里面那间。
             听镇上的人说，今早七点十分，他倒在上游闸房外，
             胸口发闷，脸朝下扣在积水里。等人赶到，他已经被抬去了医务室。」

机器稿的数字密度并不低（「邵广勤」「闸房」都含数感），但它给的是**摘要**；
定稿给的是**验尸记录**。读者拿到的是"脸朝下扣在积水里"，不是"猝死"。

差别在于：数字有没有**挂在一个具体的人、具体的时间、具体的地点上**。
挂上了，读者脑子里就有了画面；没挂上，数字只是装饰。

## 怎么测（2026-10-26 实测定标）

只认四类**硬挂靠**——定稿里的档案写法全部落在这四类里：

1. 年龄：「四十七岁」
2. 住址/位置：「二楼最里面那间」「312」「三楼」
3. 时刻：「七点十分」「18:46」「22:34」
4. 计数 + 名词：「46个账号」「12页」「19页」

实测结果（前三章，机器稿 → 人工定稿）：
    ch1  硬挂靠 16 → 23   （+44%）
    ch2  硬挂靠 36 → 27   （-25%，这章定稿偏职场日常，档案少）
    ch3  硬挂靠  3 →  9   （×3，魂穿开篇的档案信息大幅增加）

**注意 ch2 反而降了**——这不是指标失效，是真实差异：
第二章是职场日常戏，本来就没多少档案信息；
第三章是恐怖开篇，定稿把「邵广勤今早猝死」换成了完整验尸记录。
所以这个指标必须**按章读**，不能横向比较不同类型的章节。

## 裸数字不是错，是「弱」

所以这里只统计、只给提示，不报错。
门禁里它是 P1：告诉作者「你的数字还停在装饰层面」。
"""
from __future__ import annotations

import re

#: 四类硬挂靠（数字 + 挂靠单位/上下文）
#:
#: 每个模式都必须**数字紧跟**挂靠词（或挂靠词紧跟数字），
#: 否则「他走了三层楼」这种会把「三」和「层」分开也算进去。
_ARCHIVE_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    # 1) 年龄：四十七岁
    ("年龄", re.compile(r"[零一二三四五六七八九十百\d]{1,3}岁")),
    # 2) 住址/位置：二楼最里面那间 / 312 / 三楼
    ("位置", re.compile(r"[零一二三四五六七八九十百\d]{1,3}(?:楼|层|室|间|座|单元|号)")),
    # 3) 时刻：七点十分 / 18:46 / 22:34
    ("时刻", re.compile(r"(?:[零一二三四五六七八九十]{1,3}点(?:[零一二三四五六七八九十]{1,3}分)?"
                        r"|\d{1,2}[:：]\d{2})")),
    # 4) 计数 + 名词：46个账号 / 12页 / 19页
    ("计数", re.compile(r"\d+(?:\.\d+)?\s*"
                       r"(?:个|只|张|块|杯|顿|次|层|步|口|本|年|天|分|秒|点|倍|页|版|条|封|支|颗|枚|台|辆|套|双|件|根|片|扇|间|号|室|楼|米|斤|元|人|口|字|句|行|章|场|幕|封|圈|排|行|扇)")),
]

#: 供 UI 显示的分类名
ARCHIVE_KINDS = ("年龄", "位置", "时刻", "计数")


def archive_density(text: str) -> dict:
    """统计档案式数字。

    返回：
        - total：命中四类硬挂靠的总数
        - by_kind：按类别分项
        - per_k：千字密度
    """
    t = text or ""
    if not t.strip():
        return {"total": 0, "by_kind": {}, "per_k": 0.0}
    by_kind: dict[str, int] = {}
    total = 0
    for kind, pat in _ARCHIVE_PATTERNS:
        n = len(pat.findall(t))
        by_kind[kind] = n
        total += n
    chars = len(t.strip())
    return {
        "total": total,
        "by_kind": by_kind,
        "per_k": round(total * 1000 / chars, 1) if chars else 0.0,
    }


def archive_hint(text: str, min_per_k: float = 4.0) -> str:
    """给模型的提示：数字要挂上去。"""
    d = archive_density(text)
    if d["per_k"] >= min_per_k:
        return ""
    parts = "、".join(f"{k}{v}" for k, v in d["by_kind"].items() if v)
    return (
        f"档案密度 {d['per_k']} 个/千字（目标 ≥{min_per_k}；分项：{parts or '无'}）。"
        f"数字要挂在具体的人/时/物上——"
        f"「四十七岁，住在二楼最里面那间」比「今早猝死，死因还没查清」有画面得多。"
        f"**恐怖信息要给现场，不要给摘要**：读者拿到的是「脸朝下扣在积水里」，"
        f"不是「猝死」。"
    )
